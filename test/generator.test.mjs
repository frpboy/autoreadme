import assert from 'node:assert/strict';
import test from 'node:test';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cli = resolve(projectRoot, 'dist/index.js');

async function withProject(callback) {
  const root = await mkdtemp(join(tmpdir(), 'autoreadme-regression-'));
  try {
    await callback(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

function generate(root, ...options) {
  return execFileAsync(process.execPath, [cli, 'generate', ...options], { cwd: root });
}

test('detects an unclassified project and renders the default template', async () => {
  await withProject(async (root) => {
    await generate(root);
    const readme = await readFile(join(root, 'README.md'), 'utf8');

    assert.ok(readme.includes('# ' + basename(root)));
    assert.ok(readme.includes('This README was auto-generated by **AutoReadMe**.'));
    assert.ok(readme.includes('![license]('));
    assert.ok(!readme.includes('build-passing'));
  });
});

test('prints version when invoked with -v or --version flag', async () => {
  const shortResult = await execFileAsync(process.execPath, [cli, '-v']);
  assert.equal(shortResult.stdout.trim(), '0.1.0');

  const longResult = await execFileAsync(process.execPath, [cli, '--version']);
  assert.equal(longResult.stdout.trim(), '0.1.0');
});

test('detects Node projects and renders metadata, scripts, dependencies, and the Node template', async () => {
  await withProject(async (root) => {
    await writeFile(join(root, 'package.json'), JSON.stringify({
      name: 'fixture-node',
      description: 'A deterministic Node fixture',
      license: 'Apache-2.0',
      repository: { type: 'git', url: 'https://github.com/example/fixture-node.git' },
      scripts: { dev: 'vite', test: 'node --test' },
      dependencies: { vite: '^6.0.0' }
    }, null, 2));

    await generate(root);
    const readme = await readFile(join(root, 'README.md'), 'utf8');

    assert.ok(readme.includes('# fixture-node'));
    assert.ok(readme.includes('A deterministic Node fixture'));
    assert.ok(readme.includes('npm run dev'));
    assert.ok(readme.includes('npm run test'));
    assert.ok(readme.includes('vite'));
    assert.ok(readme.includes('[Repository](https://github.com/example/fixture-node.git)'));
    assert.ok(readme.includes('license-Apache-2.0'));
    assert.ok(!readme.includes('build-passing'));
  });
});

test('detects Python projects and renders requirements in the Python template', async () => {
  await withProject(async (root) => {
    await writeFile(join(root, 'requirements.txt'), 'requests==2.32.0\npydantic>=2\n');

    await generate(root);
    const readme = await readFile(join(root, 'README.md'), 'utf8');

    assert.ok(readme.includes('# ' + basename(root)));
    assert.ok(readme.includes('pip install -r requirements.txt'));
    assert.ok(readme.includes('requests==2.32.0'));
    assert.ok(readme.includes('pydantic>=2'));
    assert.ok(!readme.includes('build-passing'));
  });
});

test('does not claim a build is passing for any generated template', async () => {
  await withProject(async (root) => {
    await generate(root);
    let readme = await readFile(join(root, 'README.md'), 'utf8');
    assert.ok(!readme.includes('build-passing'));

    await writeFile(join(root, 'package.json'), JSON.stringify({ name: 'node-badge-fixture' }));
    await generate(root);
    readme = await readFile(join(root, 'README.md'), 'utf8');
    assert.ok(!readme.includes('build-passing'));

    await rm(join(root, 'package.json'));
    await writeFile(join(root, 'requirements.txt'), 'requests==2.32.0\n');
    await generate(root);
    readme = await readFile(join(root, 'README.md'), 'utf8');
    assert.ok(!readme.includes('build-passing'));
  });
});

test('falls back to the default template when an unknown template is requested', async () => {
  await withProject(async (root) => {
    await generate(root, '--template', 'rust');
    const readme = await readFile(join(root, 'README.md'), 'utf8');

    assert.ok(readme.includes('This README was auto-generated by **AutoReadMe**.'));
    assert.ok(!readme.includes('build-passing'));
  });
});

test('fails safely on malformed package metadata without writing a README', async () => {
  await withProject(async (root) => {
    await writeFile(join(root, 'package.json'), '{ malformed json');
    await assert.rejects(generate(root));
    await assert.rejects(readFile(join(root, 'README.md'), 'utf8'));
  });
});

test('handles missing optional Node metadata without emitting undefined values', async () => {
  await withProject(async (root) => {
    await writeFile(join(root, 'package.json'), JSON.stringify({ name: 'minimal-node' }));
    await generate(root);
    const readme = await readFile(join(root, 'README.md'), 'utf8');

    assert.ok(readme.includes('# minimal-node'));
    assert.ok(readme.includes('license-MIT'));
    assert.ok(!readme.includes('undefined'));
    assert.ok(!readme.includes('build-passing'));
  });
});
